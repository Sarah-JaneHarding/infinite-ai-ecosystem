#!/usr/bin/env bash
# The development and testing sandbox: one command from a clean checkout to a running, seeded,
# disposable platform — and a clean container to lint, typecheck, test and build it in.
#
#   pnpm sandbox up        generate local secrets (first time), start Postgres+Redis+Keycloak, migrate, seed
#   pnpm sandbox verify    prove the sandbox honours the platform's isolation invariants
#   pnpm sandbox check     lint + typecheck + format + unit tests, in a clean container
#   pnpm sandbox --help    everything else
#
# Design (docs/SANDBOX.md has the long version):
#   * Reuses infra/docker/compose.dev.yml; infra/sandbox/compose.sandbox.yml is a thin overlay.
#   * No secret is committed (rule 7). `env` generates infra/sandbox/.env with fresh random values;
#     git ignores it. `reset` wipes the data volumes but keeps the file, so credentials stay valid.
#   * The repository is mounted read-only into the toolbox and copied; nothing a command does in the
#     sandbox can change the host checkout.
set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/.."

PROJECT=infinite-ai-sandbox
APPS_PROJECT=infinite-ai-sandbox-apps
ENV_FILE="${SANDBOX_ENV_FILE:-infra/sandbox/.env}"
ENV_EXAMPLE="${SANDBOX_ENV_EXAMPLE:-infra/docker/.env.example}"

die() { echo "sandbox: $*" >&2; exit 1; }

compose() {
  docker compose -p "$PROJECT" --env-file "$ENV_FILE" \
    -f infra/docker/compose.dev.yml -f infra/sandbox/compose.sandbox.yml "$@"
}

# ---------------------------------------------------------------------------------------------
# Secrets
# ---------------------------------------------------------------------------------------------

# URL-safe on purpose: these values are embedded in connection strings, where `/`, `+` and `=` would
# need percent-encoding.
alnum() { openssl rand -base64 48 | tr -dc 'A-Za-z0-9' | head -c "${1:-32}"; }

# Satisfies the realm's password policy (12+ characters, upper, lower, digit, special) by construction:
# the fixed prefix supplies one of each, the rest is random.
policy_password() { printf 'Sb1!%s' "$(alnum 24)"; }

generate_env() {
  local out="$1"
  [ -f "$ENV_EXAMPLE" ] || die "$ENV_EXAMPLE not found (run from the repository)."
  command -v openssl >/dev/null || die "openssl is required to generate secrets."

  declare -A V
  V[POSTGRES_DB]=infinite_ai_sandbox
  V[POSTGRES_USER]=postgres
  V[POSTGRES_PASSWORD]=$(alnum 32)
  V[MIGRATOR_PASSWORD]=$(alnum 32)
  V[APP_RW_PASSWORD]=$(alnum 32)
  V[WORKER_RW_PASSWORD]=$(alnum 32)
  V[ANALYTICS_RO_PASSWORD]=$(alnum 32)
  V[KEYCLOAK_ADMIN]=admin
  V[KEYCLOAK_ADMIN_PASSWORD]=$(policy_password)
  V[KEYCLOAK_WEB_CLIENT_SECRET]=$(alnum 32)
  V[KEYCLOAK_WORKER_CLIENT_SECRET]=$(alnum 32)
  V[SEED_USER_PASSWORD]=$(policy_password)
  V[MINIO_ROOT_USER]=sandboxminio
  V[MINIO_ROOT_PASSWORD]=$(alnum 32)
  V[OBJECT_STORE_BUCKET]=infinite-ai-sandbox
  V[LANGFUSE_POSTGRES_USER]=langfuse
  V[LANGFUSE_POSTGRES_PASSWORD]=$(alnum 32)
  V[LANGFUSE_REDIS_PASSWORD]=$(alnum 32)
  V[LANGFUSE_CLICKHOUSE_USER]=clickhouse
  V[LANGFUSE_CLICKHOUSE_PASSWORD]=$(alnum 32)
  V[LANGFUSE_SALT]=$(alnum 32)
  V[LANGFUSE_ENCRYPTION_KEY]=$(openssl rand -hex 32)
  V[LANGFUSE_NEXTAUTH_SECRET]=$(alnum 32)
  V[LANGFUSE_INIT_PROJECT_PUBLIC_KEY]="pk-lf-sandbox-$(alnum 16)"
  V[LANGFUSE_INIT_PROJECT_SECRET_KEY]="sk-lf-sandbox-$(alnum 32)"
  V[LANGFUSE_INIT_USER_EMAIL]=sandbox@example.invalid
  V[LANGFUSE_INIT_USER_PASSWORD]=$(policy_password)
  V[NEXTAUTH_URL]=http://localhost:3000
  V[NEXTAUTH_SECRET]=$(openssl rand -base64 32)
  V[AUTH_KEYCLOAK_ID]=infinite-ai-web
  V[DB_ENCRYPTION_KEY]=$(openssl rand -base64 32)
  V[REDIS_URL]=redis://redis:6379
  V[KEYCLOAK_ISSUER]=http://host.docker.internal:8180/realms/infinite-ai
  V[OBJECT_STORE_ENDPOINT]=http://minio:9000
  # Derived: the application connects as app_rw, never the migrator (rule 5).
  V[AUTH_KEYCLOAK_SECRET]=${V[KEYCLOAK_WEB_CLIENT_SECRET]}
  V[OBJECT_STORE_ACCESS_KEY]=${V[MINIO_ROOT_USER]}
  V[OBJECT_STORE_SECRET_KEY]=${V[MINIO_ROOT_PASSWORD]}
  V[DATABASE_URL]="postgresql://app_rw:${V[APP_RW_PASSWORD]}@postgres:5432/${V[POSTGRES_DB]}"
  V[DIRECT_DATABASE_URL]=${V[DATABASE_URL]}

  umask 077
  mkdir -p "$(dirname "$out")"
  {
    echo "# Generated by scripts/sandbox.sh — local to this machine, never commit it (rule 7)."
    echo "# Regenerate by deleting this file; \`pnpm sandbox reset\` keeps it so credentials stay valid."
    local name
    while IFS= read -r name; do
      [ -n "${V[$name]+set}" ] || die "no rule for $ENV_EXAMPLE variable $name — add one to generate_env in scripts/sandbox.sh."
      printf '%s=%s\n' "$name" "${V[$name]}"
    done < <(grep -E '^[A-Z][A-Z0-9_]*=$' "$ENV_EXAMPLE" | cut -d= -f1)
  } >"$out"
  chmod 600 "$out"
}

ensure_env() {
  if [ -f "$ENV_FILE" ]; then return 0; fi
  generate_env "$ENV_FILE"
  echo "sandbox: generated $ENV_FILE (fresh random secrets; git ignores it)."
}

# ---------------------------------------------------------------------------------------------
# Preconditions
# ---------------------------------------------------------------------------------------------

need_docker() {
  command -v docker >/dev/null || die "docker is not installed."
  docker info >/dev/null 2>&1 || die "the Docker daemon is not reachable (is it running?)."
  local v
  v=$(docker compose version --short 2>/dev/null || true)
  [ -n "$v" ] || die "the Docker Compose plugin (v2.24 or later) is required."
  # `!override` in the overlay needs 2.24.
  if [ "$(printf '%s\n2.24.0\n' "${v#v}" | sort -V | head -n1)" != "2.24.0" ]; then
    die "Docker Compose $v is too old; the sandbox needs 2.24 or later."
  fi
}

# ---------------------------------------------------------------------------------------------
# Commands
# ---------------------------------------------------------------------------------------------

cmd_up() {
  need_docker; ensure_env
  compose up -d --wait postgres redis keycloak
  compose run --rm migrate
  cat <<MSG

Sandbox is up.
  Postgres   127.0.0.1:5432   (role passwords: $ENV_FILE)
  Redis      127.0.0.1:6379
  Keycloak   http://localhost:8180   (admin credentials: $ENV_FILE; dev logins use SEED_USER_PASSWORD)

Next:  pnpm sandbox verify   |   pnpm sandbox check   |   pnpm sandbox shell
MSG
}

cmd_down() {
  need_docker; ensure_env
  docker compose -p "$APPS_PROJECT" --env-file "$ENV_FILE" -f infra/docker/compose.apps.yml down 2>/dev/null || true
  compose --profile observability --profile tools down --remove-orphans
}

cmd_reset() {
  need_docker; ensure_env
  docker compose -p "$APPS_PROJECT" --env-file "$ENV_FILE" -f infra/docker/compose.apps.yml down -v 2>/dev/null || true
  compose --profile observability --profile tools down -v --remove-orphans
  echo "sandbox: data volumes removed; $ENV_FILE kept. \`pnpm sandbox up\` starts fresh."
}

in_tools() { need_docker; ensure_env; compose run --rm tools "$@"; }

cmd_apps() {
  need_docker; ensure_env
  if [ -z "${ANTHROPIC_API_KEYS:-}${OPENAI_API_KEYS:-}${GOOGLE_API_KEYS:-}${LOCAL_MODEL_BASE_URL:-}" ]; then
    die "the gateway will not boot without model credentials, and the sandbox stores none.
  Give it some in your shell for this command — nothing is written to disk:
    ANTHROPIC_API_KEYS=sk-... pnpm sandbox apps
  or LOCAL_MODEL_BASE_URL=http://host.docker.internal:11434/v1 (an OpenAI-compatible server such as Ollama).
  Use test credentials with a spend limit; the sandbox is not a place for production keys."
  fi
  # Only Anthropic given: use the routing file that names only Anthropic, or the gateway refuses to boot.
  if [ -n "${ANTHROPIC_API_KEYS:-}" ] && [ -z "${OPENAI_API_KEYS:-}${GOOGLE_API_KEYS:-}${LOCAL_MODEL_BASE_URL:-}" ]; then
    export GATEWAY_ROUTING_CONFIG="${GATEWAY_ROUTING_CONFIG:-/repo/apps/gateway/routing.anthropic.json}"
  fi
  if [ "$(uname -s)" = Linux ]; then
    echo "sandbox: on Linux the app containers reach Keycloak at host.docker.internal:8180, which needs"
    echo "  (1) '127.0.0.1 host.docker.internal' in /etc/hosts for your browser, and"
    echo "  (2) Keycloak published beyond loopback: SANDBOX_KEYCLOAK_BIND=0.0.0.0 pnpm sandbox up"
  fi
  DATA_PLANE_NETWORK="${PROJECT}_default" docker compose -p "$APPS_PROJECT" --env-file "$ENV_FILE" \
    -f infra/docker/compose.apps.yml up -d --build
  echo "sandbox: web on http://localhost:3000 (sign in as one of the dev logins in docs/DEV_SETUP.md)."
}

cmd_apps_down() {
  need_docker; ensure_env
  DATA_PLANE_NETWORK="${PROJECT}_default" docker compose -p "$APPS_PROJECT" --env-file "$ENV_FILE" \
    -f infra/docker/compose.apps.yml down
}

usage() {
  cat <<'USAGE'
pnpm sandbox <command>

  up            generate secrets (first time), start Postgres + Redis + Keycloak, migrate and seed
  down          stop everything, keep the data
  reset         stop everything and delete the data volumes (the generated secrets are kept)
  status        what is running
  logs [svc]    follow logs
  verify        smoke-test the running sandbox against the platform's isolation invariants
  check         lint + typecheck + format:check + unit tests, in a clean container
  test          unit tests only
  run <cmd...>  run any command in the toolbox, e.g.  pnpm sandbox run pnpm --filter @infinite-ai/db typecheck
  shell         an interactive shell in the toolbox
  psql          psql as the migrator role
  env           generate infra/sandbox/.env if it does not exist  (--out <file> writes elsewhere)
  doctor        check the prerequisites
  apps          build and start web + worker + gateway (needs model credentials in your shell)
  apps-down     stop them
  observability start MinIO and the Langfuse stack as well (large; opt-in)
USAGE
}

case "${1:-}" in
  up) cmd_up ;;
  down) cmd_down ;;
  reset) cmd_reset ;;
  status) need_docker; ensure_env; compose --profile observability --profile tools ps ;;
  logs) shift; need_docker; ensure_env; compose logs -f --tail=100 "$@" ;;
  verify) in_tools sandbox-verify ;;
  check) in_tools bash -c 'pnpm lint && pnpm typecheck && pnpm format:check && pnpm test' ;;
  test) in_tools pnpm test ;;
  run) shift; [ "$#" -gt 0 ] || die "run needs a command."; in_tools "$@" ;;
  shell) in_tools bash ;;
  psql) in_tools bash -c 'SANDBOX_NO_SYNC=1 psql "$MIGRATOR_DATABASE_URL"' ;;
  env)
    shift
    if [ "${1:-}" = "--out" ]; then
      [ -n "${2:-}" ] || die "--out needs a path."
      generate_env "$2"
    else
      ensure_env
    fi
    ;;
  doctor)
    command -v docker >/dev/null && echo "docker: $(docker --version)" || die "docker is not installed."
    docker info >/dev/null 2>&1 && echo "daemon: reachable" || die "the Docker daemon is not reachable."
    need_docker; echo "compose: $(docker compose version --short) (>= 2.24 required)"
    [ -f "$ENV_FILE" ] && echo "env: $ENV_FILE present" || echo "env: $ENV_FILE not yet generated (pnpm sandbox up does it)"
    ;;
  apps) cmd_apps ;;
  apps-down) cmd_apps_down ;;
  observability) need_docker; ensure_env; compose --profile observability up -d --wait ;;
  ""|-h|--help|help) usage ;;
  *) usage >&2; die "unknown command '$1'." ;;
esac
